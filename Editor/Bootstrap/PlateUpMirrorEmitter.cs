    /// <summary>Emits data shapes, not executable game logic. Source order is retained for Unity fields.</summary>
    public sealed class PlateUpMirrorEmitter
    {
        private readonly string _templates;
        private static readonly UTF8Encoding Utf8 = new UTF8Encoding(false);
        public PlateUpMirrorEmitter(string templatesDirectory) { _templates = templatesDirectory; }

        public void Emit(PlateUpMirrorModel model, string outputRoot)
        {
            if (model == null) throw new ArgumentNullException(nameof(model));
            AtomicGeneratedDirectory.ValidatePaths(outputRoot, KitchenLibStudioGeneratedPaths.AssetDirectory);
            Directory.CreateDirectory(outputRoot);
            var selected = new HashSet<string>(model.Types.Select(Key), StringComparer.Ordinal);
            foreach (IGrouping<string, TypeDefinition> assembly in model.Types.GroupBy(type => type.Module.Assembly.Name.Name))
            {
                string prefix = assembly.Key == "Kitchen.GameData" ? "" : "Dependencies/" + assembly.Key + "/";
                var references = new SortedSet<string>(StringComparer.Ordinal);
                foreach (TypeDefinition type in assembly)
                {
                    foreach (TypeReference reference in References(type))
                        foreach (TypeReference item in Expand(reference))
                        {
                            string name = item.Scope?.Name;
                            if (name != assembly.Key && (name == "Unity.TextMeshPro" || name == "Sirenix.Serialization"
                                || model.Types.Any(candidate => candidate.Module.Assembly.Name.Name == name))) references.Add(name);
                        }
                }
                Write(outputRoot, prefix + assembly.Key + ".asmdef", "{\n  \"name\": " + Quote(assembly.Key)
                    + ",\n  \"references\": [" + string.Join(", ", references.Select(Quote)) + "]\n}\n");
                foreach (TypeDefinition type in assembly.Where(type => type.DeclaringType == null))
                {
                    var source = new StringBuilder("// <auto-generated />\n// Data-only mirror. Game methods are deliberately not executed in the authoring editor.\n#pragma warning disable 0169, 0649, 0108, 0114\n");
                    bool hasNamespace = !string.IsNullOrEmpty(type.Namespace);
                    if (hasNamespace) source.Append("namespace ").Append(Namespace(type.Namespace)).Append("\n{\n");
                    EmitType(source, type, selected);
                    if (hasNamespace) source.Append("}\n");
                    Write(outputRoot, prefix + "Types/" + type.Namespace.Replace('.', '/') + "/" + type.Name + ".cs", source.ToString());
                }
            }
            CopyTemplate(outputRoot, "Sirenix.Serialization.asmdef", "Sirenix/Sirenix.Serialization.asmdef");
            foreach (string file in Directory.GetFiles(Path.Combine(_templates, "Sirenix"), "*.cs").OrderBy(path => path, StringComparer.Ordinal))
                Write(outputRoot, "Sirenix/" + Path.GetFileName(file), File.ReadAllText(file));

            Schema schema = BuildSchema(model);
            string canonical = Json(schema);
            schema.globalFingerprint = PlateUpSchemaFingerprint.HashText(canonical);
            Write(outputRoot, "plateup-schema.json", Json(schema) + "\n");
            string contracts = File.ReadAllText(Path.Combine(_templates, "DescriptorContracts.txt"));
            Write(outputRoot, "GdoSchemaRegistry.g.cs", Registry(schema, canonical, contracts, "KitchenLib.Studio.Generated"));
            Write(outputRoot, "Linker/GdoSchemaRegistry.g.cs", Registry(schema, canonical, contracts, "KitchenLib.Studio.Linker.Generated"));
            string[] overlayFields = schema.types.SelectMany(type => type.fields.Select(field =>
                type.runtimeTypeName + "|" + field.name + "|" + field.runtimeTypeName + "|" + field.classification)).ToArray();
            Write(outputRoot, "Linker/SupportedOverlaySchema.g.cs", "// <auto-generated />\nnamespace KitchenLib.Studio.Linker.Generated\n{\n"
                + "internal static class SupportedOverlaySchema\n{\ninternal const string Fingerprint = " + Quote(schema.globalFingerprint)
                + ";\ninternal static readonly string[] Fields = " + Strings(overlayFields) + ";\n}\n}\n");
            WriteMetadata(outputRoot);
        }

        private static IEnumerable<TypeReference> References(TypeDefinition type)
        {
            if (type.BaseType != null) yield return type.BaseType;
            foreach (FieldDefinition field in PlateUpMirrorModel.Fields(type)) yield return field.FieldType;
            foreach (PropertyDefinition property in PlateUpMirrorModel.Properties(type)) yield return property.PropertyType;
            foreach (GenericParameter parameter in type.GenericParameters)
                foreach (GenericParameterConstraint constraint in parameter.Constraints) yield return constraint.ConstraintType;
        }

        private static IEnumerable<TypeReference> Expand(TypeReference type)
        {
            if (type is GenericParameter) yield break;
            if (type is GenericInstanceType generic)
            {
                foreach (TypeReference argument in generic.GenericArguments)
                    foreach (TypeReference item in Expand(argument)) yield return item;
            }
            if (type is TypeSpecification specification)
            { foreach (TypeReference item in Expand(specification.ElementType)) yield return item; }
            else yield return type;
        }

        private static void EmitType(StringBuilder source, TypeDefinition type, ISet<string> selected)
        {
            if (type.IsSerializable && !type.IsEnum) source.Append("[global::System.Serializable]\n");
            if (PlateUpMirrorModel.HasAttribute(type, "System.FlagsAttribute")) source.Append("[global::System.Flags]\n");
            if (type.IsEnum)
            {
                source.Append("public enum ").Append(Identifier(type.Name)).Append(" : ")
                    .Append(TypeName(type.Fields.Single(field => field.Name == "value__").FieldType)).Append("\n{\n");
                foreach (FieldDefinition field in type.Fields.Where(field => field.IsLiteral))
                    source.Append(Identifier(field.Name)).Append(" = ").Append(Constant(field.Constant)).Append(",\n");
            }
            else
            {
                source.Append("public ");
                if (!type.IsValueType && !type.IsInterface && type.IsAbstract) source.Append("abstract ");
                source.Append(type.IsInterface ? "interface " : type.IsValueType ? "struct " : "class ").Append(Identifier(type.Name));
                if (type.HasGenericParameters) source.Append('<').Append(string.Join(", ", type.GenericParameters.Select(parameter => Identifier(parameter.Name)))).Append('>');
                if (!type.IsInterface && !type.IsValueType && type.BaseType != null && type.BaseType.FullName != "System.Object")
                    source.Append(" : ").Append(TypeName(type.BaseType));
                foreach (GenericParameter parameter in type.GenericParameters)
                {
                    var constraints = new List<string>();
                    if (parameter.HasNotNullableValueTypeConstraint) constraints.Add("struct");
                    else if (parameter.HasReferenceTypeConstraint) constraints.Add("class");
                    foreach (GenericParameterConstraint constraint in parameter.Constraints)
                        // Interfaces describe behavior, not serialized shape; game methods are not reproduced.
                        if (constraint.ConstraintType.FullName != "System.ValueType" && constraint.ConstraintType.Resolve()?.IsInterface != true)
                            constraints.Add(TypeName(constraint.ConstraintType));
                    if (parameter.HasDefaultConstructorConstraint && !parameter.HasNotNullableValueTypeConstraint) constraints.Add("new()");
                    if (constraints.Count != 0) source.Append("\nwhere ").Append(Identifier(parameter.Name)).Append(" : ").Append(string.Join(", ", constraints));
                }
                source.Append("\n{\n");
                foreach (FieldDefinition field in PlateUpMirrorModel.Fields(type))
                {
                    if (field.Name.StartsWith("<", StringComparison.Ordinal))
                    {
                        if (type.Properties.Any(property => field.Name == "<" + property.Name + ">k__BackingField")) continue;
                        throw new NotSupportedException("A serialized compiler-generated field needs a matching source representation: " + field.FullName);
                    }
                    EmitAttributes(source, field);
                    if (field.IsNotSerialized) source.Append("[global::System.NonSerialized]\n");
                    source.Append(field.IsPublic ? "public " : "private ");
                    if (field.IsInitOnly) source.Append("readonly ");
                    source.Append(TypeName(field.FieldType)).Append(' ').Append(Identifier(field.Name)).Append(";\n");
                }
                foreach (PropertyDefinition property in PlateUpMirrorModel.Properties(type))
                {
                    FieldDefinition backing = PlateUpMirrorModel.Fields(type).FirstOrDefault(field => field.Name == "<" + property.Name + ">k__BackingField");
                    if (backing != null) EmitAttributes(source, backing, "field: ");
                    bool isPublic = property.GetMethod?.IsPublic == true || property.SetMethod?.IsPublic == true;
                    source.Append(type.IsInterface ? "" : isPublic ? "public " : "private ").Append(TypeName(property.PropertyType)).Append(' ').Append(Identifier(property.Name)).Append(" { ");
                    if (property.GetMethod != null)
                    {
                        if (isPublic && !property.GetMethod.IsPublic) source.Append("private ");
                        source.Append(type.IsInterface || backing != null ? "get; " : "get { return default(" + TypeName(property.PropertyType) + "); } ");
                    }
                    if (property.SetMethod != null)
                    {
                        if (isPublic && !property.SetMethod.IsPublic) source.Append("private ");
                        source.Append(type.IsInterface || backing != null ? "set; " : "set { } ");
                    }
                    source.Append("}\n");
                }
                foreach (TypeDefinition nested in type.NestedTypes.Where(nested => selected.Contains(Key(nested))).OrderBy(nested => nested.Name, StringComparer.Ordinal))
                    EmitType(source, nested, selected);
            }
            source.Append("}\n");
        }

        private static void EmitAttributes(StringBuilder source, FieldDefinition field, string target = "")
        {
            foreach (CustomAttribute attribute in field.CustomAttributes)
            {
                string name = attribute.AttributeType.FullName;
                if (!name.StartsWith("UnityEngine.", StringComparison.Ordinal) && name != "Sirenix.Serialization.OdinSerializeAttribute") continue;
                var arguments = attribute.ConstructorArguments.Select(AttributeArgument).ToList();
                arguments.AddRange(attribute.Fields.Select(argument => Identifier(argument.Name) + " = " + AttributeArgument(argument.Argument)));
                arguments.AddRange(attribute.Properties.Select(argument => Identifier(argument.Name) + " = " + AttributeArgument(argument.Argument)));
                source.Append('[').Append(target).Append(TypeName(attribute.AttributeType)).Append('(').Append(string.Join(", ", arguments)).Append(")]\n");
            }
        }

        private static string AttributeArgument(CustomAttributeArgument argument)
        {
            if (argument.Value is TypeReference type) return "typeof(" + TypeName(type) + ")";
            if (argument.Value is CustomAttributeArgument[] array) return "new " + TypeName(argument.Type) + " { " + string.Join(", ", array.Select(AttributeArgument)) + " }";
            if (argument.Value != null && argument.Type.Resolve()?.IsEnum == true) return "(" + TypeName(argument.Type) + ")" + Constant(argument.Value);
            return Constant(argument.Value);
        }

        internal static string TypeName(TypeReference type)
        {
            if (type is GenericParameter) return Identifier(type.Name);
            if (type is ArrayType array) return TypeName(array.ElementType) + "[" + new string(',', array.Rank - 1) + "]";
            if (type is GenericInstanceType generic)
                return TypeName(generic.ElementType) + "<" + string.Join(", ", generic.GenericArguments.Select(TypeName)) + ">";
            if (type is TypeSpecification) throw new NotSupportedException("Unsupported data type specification: " + type.FullName);
            if (type.DeclaringType != null) return TypeName(type.DeclaringType) + "." + Identifier(type.Name);
            return "global::" + (string.IsNullOrEmpty(type.Namespace) ? "" : Namespace(type.Namespace) + ".") + Identifier(type.Name);
        }

        private static string Namespace(string value) => string.Join(".", value.Split('.').Select(Identifier));
        private static string Identifier(string value)
        {
            int arity = value.IndexOf('`'); if (arity >= 0) value = value.Substring(0, arity);
            if (value.Length == 0 || !(char.IsLetter(value[0]) || value[0] == '_') || value.Any(character => !(char.IsLetterOrDigit(character) || character == '_')))
                throw new NotSupportedException("Cannot represent metadata identifier in C#: " + value);
            return "@" + value;
        }
        private static string Key(TypeDefinition type) => type.Module.Assembly.Name.Name + ":" + type.FullName;
        private static string RuntimeName(TypeReference type) => type?.FullName.Replace('/', '+');
        private static string Constant(object value)
        {
            if (value == null) return "null";
            if (value is string text) return Quote(text);
            if (value is char character) return "(char)" + (int)character;
            if (value is bool boolean) return boolean ? "true" : "false";
            if (value is float single)
                return float.IsNaN(single) ? "float.NaN" : float.IsPositiveInfinity(single) ? "float.PositiveInfinity" : float.IsNegativeInfinity(single) ? "float.NegativeInfinity" : single.ToString("R", CultureInfo.InvariantCulture) + "f";
            if (value is double number)
                return double.IsNaN(number) ? "double.NaN" : double.IsPositiveInfinity(number) ? "double.PositiveInfinity" : double.IsNegativeInfinity(number) ? "double.NegativeInfinity" : number.ToString("R", CultureInfo.InvariantCulture) + "d";
            return Convert.ToString(value, CultureInfo.InvariantCulture) + (value is ulong ? "UL" : value is long ? "L" : value is uint ? "U" : "");
        }

        internal static string Quote(string value)
        {
            if (value == null) return "null";
            var result = new StringBuilder("\"");
            foreach (char character in value)
            {
                switch (character)
                {
                    case '"': result.Append("\\\""); break;
                    case '\\': result.Append("\\\\"); break;
                    case '\n': result.Append("\\n"); break;
                    case '\r': result.Append("\\r"); break;
                    case '\t': result.Append("\\t"); break;
                    default:
                        if (character < 32 || character > 126) result.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
                        else result.Append(character);
                        break;
                }
            }
            return result.Append('"').ToString();
        }

        private void CopyTemplate(string root, string template, string destination) => Write(root, destination, File.ReadAllText(Path.Combine(_templates, template)));
        private static void Write(string root, string relative, string content)
        {
            string path = Path.Combine(root, relative);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, content.Replace("\r\n", "\n"), Utf8);
        }

        private static void WriteMetadata(string root)
        {
            foreach (string path in Directory.GetFiles(root, "*", SearchOption.AllDirectories).OrderBy(path => path, StringComparer.Ordinal))
            {
                string relative = path.Substring(root.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Replace('\\', '/');
                string guid = PlateUpSchemaFingerprint.HashText("KitchenLibStudio.Generated/" + relative).Substring(0, 32).ToLowerInvariant();
                File.WriteAllText(path + ".meta", "fileFormatVersion: 2\nguid: " + guid + "\n", Utf8);
            }
            foreach (string directory in Directory.GetDirectories(root, "*", SearchOption.AllDirectories).OrderBy(path => path, StringComparer.Ordinal))
            {
                string relative = directory.Substring(root.Length).Replace('\\', '/');
                string guid = PlateUpSchemaFingerprint.HashText("KitchenLibStudio.Generated" + relative).Substring(0, 32).ToLowerInvariant();
                File.WriteAllText(directory + ".meta", "fileFormatVersion: 2\nguid: " + guid + "\nfolderAsset: yes\n", Utf8);
            }
        }

        [Serializable] private sealed class Schema
        {
            public int schemaVersion = 4;
            public string sourceAssembly = "Kitchen.GameData", sourceSha256, sourceFingerprint, globalFingerprint;
            public string[] sourceAssemblies;
            public TypeSchema[] types;
            public Mapping[] runtimeMappings;
        }
        [Serializable] private sealed class TypeSchema
        {
            public string runtimeTypeName, assemblyName, baseTypeName, kind, descriptorFingerprint;
            public bool isAbstract, isCreatable, isSerializable;
            public string[] genericParameters, interfaces, serializationAttributes;
            public FieldSchema[] fields;
            public PropertySchema[] properties;
            public string[] enumValues;
        }
        [Serializable] private sealed class FieldSchema
        {
            public string name, runtimeTypeName, classification, visibility;
            public bool isNonSerialized, isReadonly;
            public string[] serializationAttributes;
            public ValueSchema value;
        }
        [Serializable] private sealed class PropertySchema
        { public string name, runtimeTypeName; public bool canRead, canWrite; public string[] serializationAttributes; }
        [Serializable] private sealed class ValueSchema
        {
            public string kind, runtimeTypeName, expectedTypeName;
            public ValueSchema element;
            public MemberSchema[] members = Array.Empty<MemberSchema>();
            public string[] enumValues = Array.Empty<string>();
        }
        [Serializable] private sealed class MemberSchema { public string name; public ValueSchema value; }
        [Serializable] private sealed class Mapping { public string declaringTypeName, authoringFieldName, runtimeFieldName, populationMethod; }

        private static Schema BuildSchema(PlateUpMirrorModel model)
        {
            var schema = new Schema { sourceSha256 = model.SourceSha256, sourceFingerprint = model.SourceFingerprint,
                sourceAssemblies = model.SourceAssemblies.ToArray() };
            schema.types = model.Types.Select(type =>
            {
                var data = new TypeSchema {
                    runtimeTypeName = RuntimeName(type), assemblyName = type.Module.Assembly.Name.Name, baseTypeName = RuntimeName(type.BaseType),
                    kind = type.IsEnum ? "Enum" : type.IsInterface ? "Interface" : type.IsValueType ? "Struct" : "Class",
                    isAbstract = type.IsAbstract, isCreatable = !type.IsAbstract && !type.HasGenericParameters && PlateUpMirrorModel.IsGameDataObject(type),
                    isSerializable = type.IsSerializable,
                    genericParameters = type.GenericParameters.Select(parameter => parameter.Name + ":" + parameter.Attributes + ":"
                        + string.Join(",", parameter.Constraints.Select(constraint => RuntimeName(constraint.ConstraintType)))).ToArray(),
                    interfaces = type.Interfaces.Select(item => RuntimeName(item.InterfaceType)).OrderBy(name => name, StringComparer.Ordinal).ToArray(),
                    serializationAttributes = Attributes(type), enumValues = EnumValues(type),
                    fields = PlateUpMirrorModel.Fields(type).Select(field => {
                        ValueSchema value = Describe(field.FieldType, new HashSet<string>(StringComparer.Ordinal));
                        return new FieldSchema { name = field.Name, runtimeTypeName = RuntimeName(field.FieldType), visibility = field.IsPublic ? "Public" : "Private",
                            isNonSerialized = field.IsNotSerialized, isReadonly = field.IsInitOnly, serializationAttributes = Attributes(field), value = value,
                            classification = field.IsNotSerialized ? "RuntimeDerived" : Contains(value, "Unsupported") ? "Unsupported" : Contains(value, "GdoReference") ? "Linked" : "Native" };
                    }).ToArray(),
                    properties = PlateUpMirrorModel.Properties(type).Select(property => new PropertySchema { name = property.Name,
                        runtimeTypeName = RuntimeName(property.PropertyType), canRead = property.GetMethod != null, canWrite = property.SetMethod != null,
                        serializationAttributes = Attributes(property) }).ToArray()
                };
                data.descriptorFingerprint = PlateUpSchemaFingerprint.HashText(Json(data));
                return data;
            }).ToArray();
            schema.runtimeMappings = model.Types.SelectMany(RuntimeMappings).OrderBy(mapping => mapping.declaringTypeName, StringComparer.Ordinal)
                .ThenBy(mapping => mapping.authoringFieldName, StringComparer.Ordinal).ThenBy(mapping => mapping.runtimeFieldName, StringComparer.Ordinal)
                .ThenBy(mapping => mapping.populationMethod, StringComparer.Ordinal).ToArray();
            return schema;
        }

        private static string[] Attributes(Mono.Cecil.ICustomAttributeProvider provider) => provider.CustomAttributes.Select(attribute =>
            attribute.AttributeType.FullName + "(" + string.Join(",", attribute.ConstructorArguments.Select(AttributeArgument)
                .Concat(attribute.Fields.Select(argument => argument.Name + "=" + AttributeArgument(argument.Argument)))
                .Concat(attribute.Properties.Select(argument => argument.Name + "=" + AttributeArgument(argument.Argument)))) + ")")
            .OrderBy(value => value, StringComparer.Ordinal).ToArray();
        private static string[] EnumValues(TypeDefinition type) => !type.IsEnum ? Array.Empty<string>() : type.Fields.Where(field => field.IsLiteral)
            .Select(field => field.Name + "=" + Convert.ToString(field.Constant, CultureInfo.InvariantCulture)).ToArray();

        private static ValueSchema Describe(TypeReference type, ISet<string> visiting)
        {
            var value = new ValueSchema { runtimeTypeName = RuntimeName(type), kind = "Unsupported" };
            if (type is GenericParameter) return value;
            if (type.FullName == "System.String") { value.kind = "String"; return value; }
            if (type.IsPrimitive && type.MetadataType != MetadataType.IntPtr && type.MetadataType != MetadataType.UIntPtr)
            { value.kind = "Scalar"; return value; }
            if (type is ArrayType array)
            {
                if (array.Rank == 1) { value.kind = "Array"; value.element = Describe(array.ElementType, visiting); }
                return value;
            }
            if (type is GenericInstanceType generic)
            {
                string name = generic.ElementType.FullName;
                if (name == "System.Collections.Generic.List`1" || name == "System.Collections.Generic.HashSet`1")
                { value.kind = name.Contains("HashSet") ? "Set" : "List"; value.element = Describe(generic.GenericArguments[0], visiting); return value; }
                if (IsLocalizationMap(generic)) { value.kind = "LocalizationMap"; return value; }
            }
            TypeDefinition resolved = type.Resolve();
            if (resolved == null) return value;
            if (resolved.IsEnum) { value.kind = "Enum"; value.enumValues = EnumValues(resolved); return value; }
            if (PlateUpMirrorModel.IsGameDataObject(type)) { value.kind = "GdoReference"; value.expectedTypeName = RuntimeName(type); return value; }
            if (PlateUpMirrorModel.DerivesFrom(type, "UnityEngine.Object")) { value.kind = "UnityObject"; return value; }
            if (resolved.IsValueType && visiting.Count < 16 && visiting.Add(type.FullName))
            {
                value.kind = "Struct";
                value.members = PlateUpMirrorModel.Fields(resolved).Where(field => !field.IsNotSerialized).Select(field =>
                    new MemberSchema { name = field.Name, value = Describe(field.FieldType, visiting) }).ToArray();
                visiting.Remove(type.FullName);
            }
            return value;
        }

        private static bool IsLocalizationMap(GenericInstanceType type)
        {
            // Structural recognition of the game's locale-to-information wrapper; no build-specific type list.
            FieldDefinition[] fields = PlateUpMirrorModel.Fields(type.Resolve()).Where(field => !field.IsNotSerialized).ToArray();
            if (fields.Length != 1 || !(fields[0].FieldType is GenericInstanceType dictionary)
                || dictionary.ElementType.FullName != "System.Collections.Generic.Dictionary`2"
                || dictionary.GenericArguments[0].Resolve()?.IsEnum != true) return false;
            TypeReference item = dictionary.GenericArguments[1];
            if (item is GenericParameter parameter)
                item = parameter.Constraints.Select(constraint => constraint.ConstraintType).FirstOrDefault(constraint => constraint.Resolve()?.IsInterface != true);
            if (item == null) return false;
            TypeDefinition definition = item.Resolve();
            return definition != null && PlateUpMirrorModel.Fields(definition).Any(field => field.Name == "Locale"
                && field.FieldType.FullName == dictionary.GenericArguments[0].FullName);
        }

        private static bool Contains(ValueSchema value, string kind) => value.kind == kind ||
            (value.element != null && Contains(value.element, kind)) || value.members.Any(member => Contains(member.value, kind));

        private static IEnumerable<Mapping> RuntimeMappings(TypeDefinition type)
        {
            // Recognize a field read, collection copy constructor, or instance selection call whose
            // receiver is that field. Do not infer mappings across branches, locals, or arbitrary IL.
            foreach (MethodDefinition method in type.Methods.Where(method => method.HasBody))
            {
                Instruction[] instructions = method.Body.Instructions.Where(instruction => instruction.OpCode != OpCodes.Nop).ToArray();
                for (int index = 1; index < instructions.Length; index++)
                {
                    if (instructions[index].OpCode != OpCodes.Stfld) continue;
                    var target = instructions[index].Operand as FieldReference;
                    int cursor = index - 1;
                    FieldReference source = SourceField(instructions, ref cursor);
                    if (target?.DeclaringType.GetElementType().FullName != type.FullName || source?.DeclaringType.GetElementType().FullName != type.FullName
                        || cursor < 0 || instructions[cursor].OpCode != OpCodes.Ldarg_0) continue;
                    if (target.Resolve().IsNotSerialized && PlateUpMirrorModel.Fields(type).Any(field => field.Name == source.Name && !field.IsNotSerialized))
                        yield return new Mapping { declaringTypeName = RuntimeName(type), authoringFieldName = source.Name,
                            runtimeFieldName = target.Name, populationMethod = method.Name };
                }
            }
        }

        private static FieldReference SourceField(Instruction[] instructions, ref int cursor)
        {
            if (cursor < 1) return null;
            Instruction expression = instructions[cursor--];
            if (expression.OpCode == OpCodes.Ldfld && instructions[cursor].OpCode == OpCodes.Ldarg_0)
            { cursor--; return expression.Operand as FieldReference; }
            if (expression.OpCode == OpCodes.Newobj && expression.Operand is MethodReference constructor
                && constructor.Parameters.Count == 1 && constructor.DeclaringType is GenericInstanceType collection
                && (collection.ElementType.FullName == "System.Collections.Generic.List`1" || collection.ElementType.FullName == "System.Collections.Generic.HashSet`1"))
            {
                FieldReference source = SourceField(instructions, ref cursor);
                return source?.FieldType.FullName == collection.FullName ? source : null;
            }
            if (expression.OpCode == OpCodes.Callvirt && expression.Operand is MethodReference selector && selector.HasThis
                && selector.ReturnType.MetadataType != MetadataType.Void)
            {
                for (int argument = 0; argument < selector.Parameters.Count; argument++)
                {
                    if (cursor < 0) return null;
                    Code code = instructions[cursor--].OpCode.Code;
                    if (code != Code.Ldarg && code != Code.Ldarg_S && code != Code.Ldarg_0 && code != Code.Ldarg_1 && code != Code.Ldarg_2 && code != Code.Ldarg_3)
                        return null;
                }
                FieldReference source = SourceField(instructions, ref cursor);
                return source?.FieldType.FullName == selector.DeclaringType.FullName ? source : null;
            }
            return null;
        }

        private static string Registry(Schema schema, string canonical, string contracts, string namespaceName)
        {
            var source = new StringBuilder("// <auto-generated />\nnamespace " + namespaceName + "\n{\n" + contracts + "\npublic static class GdoSchemaRegistry\n{\n");
            source.Append("public const int SchemaVersion = ").Append(schema.schemaVersion).Append(";\npublic const string GlobalFingerprint = ").Append(Quote(schema.globalFingerprint))
                .Append(";\npublic const string CanonicalProjectionBase64 = ").Append(Quote(Convert.ToBase64String(Utf8.GetBytes(canonical)))).Append(";\n");
            source.Append("public static readonly string[] TypeFingerprints = ").Append(Strings(schema.types.Select(type => type.runtimeTypeName + "|" + type.descriptorFingerprint))).Append(";\n");
            source.Append("public static readonly GdoRuntimeFieldMappingData[] RuntimeMappings = new GdoRuntimeFieldMappingData[] {\n");
            foreach (Mapping mapping in schema.runtimeMappings)
                source.Append("new GdoRuntimeFieldMappingData(").Append(Quote(mapping.declaringTypeName)).Append(',').Append(Quote(mapping.authoringFieldName)).Append(',')
                    .Append(Quote(mapping.runtimeFieldName)).Append(',').Append(Quote(mapping.populationMethod)).Append("),\n");
            source.Append("};\npublic static readonly GdoTypeDescriptorData[] Types = new GdoTypeDescriptorData[] {\n");
            foreach (TypeSchema type in schema.types)
            {
                source.Append("new GdoTypeDescriptorData(").Append(Quote(type.runtimeTypeName)).Append(',').Append(Quote(type.baseTypeName)).Append(',')
                    .Append(type.isAbstract ? "true" : "false").Append(',').Append(type.isCreatable ? "true" : "false").Append(",\"Available\", new GdoDiagnosticData[] {");
                foreach (FieldSchema field in type.fields.Where(field => field.classification == "Unsupported"))
                    source.Append("new GdoDiagnosticData(").Append(Quote(field.name)).Append(',').Append(Quote("This installed field is preserved in the mirror, but its value shape is not supported by the overlay editor.")).Append("),");
                source.Append("}, new GdoFieldDescriptorData[] {\n");
                foreach (FieldSchema field in type.fields.Where(field => !field.isNonSerialized))
                    source.Append("new GdoFieldDescriptorData(").Append(Quote(type.runtimeTypeName)).Append(',').Append(Quote(field.name)).Append(',')
                        .Append(Quote(field.classification)).Append(",false,").Append(ValueCode(field.value)).Append("),\n");
                source.Append("},").Append(Quote(type.descriptorFingerprint)).Append("),\n");
            }
            return source.Append("};\n}\n}\n").ToString();
        }
        private static string ValueCode(ValueSchema value) => "new GdoValueDescriptorData(" + Quote(value.kind) + "," + Quote(value.runtimeTypeName)
            + "," + Quote(value.expectedTypeName) + "," + (value.element == null ? "null" : ValueCode(value.element))
            + ",new GdoValueMemberDescriptorData[] {" + string.Join(",", value.members.Select(member => "new GdoValueMemberDescriptorData(" + Quote(member.name) + "," + ValueCode(member.value) + ")"))
            + "}," + Strings(value.enumValues) + ")";
        private static string Strings(IEnumerable<string> values) => "new string[] {" + string.Join(",", values.Select(Quote)) + "}";

        // Unity's by-value serializer expands recursive null members to its depth limit. Schema trees need
        // explicit nulls, so encode these internal field-only records without Unity serialization callbacks.
        private static string Json(object value)
        {
            if (value == null) return "null";
            if (value is string text) return Quote(text);
            if (value is bool boolean) return boolean ? "true" : "false";
            if (value is int number) return number.ToString(CultureInfo.InvariantCulture);
            if (value is System.Collections.IEnumerable sequence)
                return "[" + string.Join(",", sequence.Cast<object>().Select(Json)) + "]";
            return "{" + string.Join(",", value.GetType().GetFields(BindingFlags.Instance | BindingFlags.Public)
                .OrderBy(field => field.MetadataToken).Select(field => Quote(field.Name) + ":" + Json(field.GetValue(value)))) + "}";
        }
    }
